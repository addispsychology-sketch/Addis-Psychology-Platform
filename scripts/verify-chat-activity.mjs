import {createClient} from '@supabase/supabase-js';
import {readFileSync} from 'node:fs';
const state=JSON.parse(readFileSync('.env.qa-session.json','utf8'));
const db=createClient(process.env.NEXT_PUBLIC_SUPABASE_URL,process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY,{auth:{persistSession:false,autoRefreshToken:false}});
const user=state.users[process.argv.includes('--client')?0:1];
const activity=process.argv.includes('--typing')?'typing':'recording';
const {error}=await db.auth.signInWithPassword({email:user.email,password:'QA-only-Addis-2026!b7kz9'});
if(error)throw new Error('QA sign-in failed');
await db.rpc('touch_activity');
const channel=db.channel('typing:'+state.conversation,{config:{private:true}});
channel.on('broadcast',{event:'activity'},({payload})=>{if(payload.user!==user.id)console.log('Received other participant activity:',payload.state);});
await new Promise((resolve,reject)=>{const timeout=setTimeout(()=>reject(new Error('No subscription')),10000);channel.subscribe(status=>{if(status==='SUBSCRIBED'){clearTimeout(timeout);resolve();}});});
console.log(`${user.role} online. Broadcasting ${activity} indicator for browser verification.`);
const send=()=>channel.send({type:'broadcast',event:'activity',payload:{user:user.id,state:activity}});
channel.on('broadcast',{event:'activity-request'},()=>void send());
await send();const interval=setInterval(()=>void send(),2000);
await new Promise(resolve=>setTimeout(resolve,55000));clearInterval(interval);
await channel.send({type:'broadcast',event:'activity',payload:{user:user.id,state:'idle'}});
await db.removeChannel(channel);await db.auth.signOut();process.exit(0);
